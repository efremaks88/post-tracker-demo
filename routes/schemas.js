bulkSchema=bulkSchema.superRefine((data,ctx)=>{
  for(const key of ['projects','series','tasks','people','roles','stages','stageGroups','achievements','personAbsences']){
    const ids=new Set();
    (data[key]||[]).forEach((item,index)=>{
      const id=String(item.id);
      if(ids.has(id))ctx.addIssue({code:'custom',path:[key,index,'id'],message:'Повторяется идентификатор записи'});
      ids.add(id);
    });
  }
});

function validate(schema) {
  return function(req, res, next) {
    var result = schema.safeParse(req.body);
    if (!result.success) {
      var errList = result.error.issues.map(function(e) {
        return { field: e.path.join('.'), msg: e.message };
      });
      console.error('[VALIDATE]', JSON.stringify(errList));
      return res.status(400).json({ error: 'Validation error', details: errList });
    }
    req.body = result.data;
    next();
  };
}

