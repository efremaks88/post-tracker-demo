const { z } = require('zod');
const { validDay, validBirthday } = require('../lib/validation');
const { containsSensitiveProjectInput } = require('../lib/project-secrets');

// Zod schemas
var projectSchema = z.object({
  id: z.string().min(1),
  name: z.string().min(1).max(200),
  abbr: z.string().max(20).default(''),
  description: z.string().max(2000).default(''),
  color: z.string().regex(/^#[0-9a-fA-F]{6}$/).default('#6366f1'),
  status: z.string().default('. . .'),
  manager: z.string().default(''),
  season: z.string().default(''),
  dossier: z.any().default({}),
  managers: z.array(z.object({ uid: z.string().optional(), name: z.string().optional() })).optional(),
  deleted: z.boolean().optional(),
  _updatedAt: z.number().optional(),
  updatedAt: z.string().optional(),
}).superRefine(function(project, ctx) {
  if (containsSensitiveProjectInput(project)) {
    ctx.addIssue({
      code: 'custom',
      path: ['dossier'],
      message: 'Project credentials cannot be sent through the shared API',
    });
  }
});

