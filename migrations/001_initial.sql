-- PPT Tracker: Initial schema
-- Created from current database state

CREATE TABLE IF NOT EXISTS users (
  id SERIAL PRIMARY KEY,
  sam_name VARCHAR(64) NOT NULL UNIQUE,
  display_name VARCHAR(255),
  email VARCHAR(255),
  role VARCHAR(20) NOT NULL DEFAULT 'viewer',
  ad_groups TEXT[] DEFAULT '{}',
  avatar_url TEXT,
  created_at TIMESTAMP DEFAULT NOW(),
  last_login TIMESTAMP,
  ad_enabled BOOLEAN NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS user_projects (
  id SERIAL PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  project_id VARCHAR(64) NOT NULL,
  can_view BOOLEAN DEFAULT true,
  can_edit BOOLEAN DEFAULT false,
  assigned_by INTEGER REFERENCES users(id),
  assigned_at TIMESTAMP DEFAULT NOW(),
  UNIQUE (user_id, project_id)
);

CREATE INDEX IF NOT EXISTS idx_user_projects_user ON user_projects(user_id);
CREATE INDEX IF NOT EXISTS idx_user_projects_project ON user_projects(project_id);

CREATE TABLE IF NOT EXISTS projects (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL DEFAULT '',
  abbr TEXT DEFAULT '',
  description TEXT DEFAULT '',
  color TEXT NOT NULL DEFAULT '#3b82f6',
  status TEXT DEFAULT 'в работе',
  manager TEXT DEFAULT '',
  season TEXT DEFAULT '',
  dossier JSONB DEFAULT '{}',
  deleted BOOLEAN DEFAULT false,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS series (
  id TEXT PRIMARY KEY,
  project_id TEXT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  name TEXT NOT NULL DEFAULT '',
  "order" INTEGER DEFAULT 0,
  shoot_start TEXT DEFAULT '',
  shoot_end TEXT DEFAULT '',
  edit_start TEXT DEFAULT '',
  pre_otk_date TEXT DEFAULT '',
  otk_date TEXT DEFAULT '',
  send_date TEXT DEFAULT '',
  air_mode TEXT DEFAULT 'weekly',
  air_day INTEGER DEFAULT 1,
  air_time TEXT DEFAULT '21:00',
  air_date TEXT DEFAULT '',
  sync_start TEXT DEFAULT '',
  transit_code TEXT DEFAULT '',
  transit_variants JSONB DEFAULT '["", "", ""]',
  stage_ranges JSONB DEFAULT '{}',
  checklists JSONB DEFAULT '[]',
  notes TEXT DEFAULT '',
  delivered BOOLEAN DEFAULT false,
  delivered_at TEXT DEFAULT '',
  assets JSONB DEFAULT '[]',
  deleted BOOLEAN DEFAULT false,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_series_project ON series(project_id);

CREATE TABLE IF NOT EXISTS tasks (
  id BIGSERIAL PRIMARY KEY,
  project_id TEXT NOT NULL,
  series_id TEXT,
  person TEXT DEFAULT '',
  status TEXT NOT NULL,
  day TEXT NOT NULL,
  "from" INTEGER DEFAULT 10,
  "to" INTEGER DEFAULT 19,
  note TEXT DEFAULT '',
  series TEXT DEFAULT '',
  autogenerated BOOLEAN DEFAULT false,
  unplanned BOOLEAN DEFAULT false,
  shifts_tail BOOLEAN DEFAULT false,
  updated_at TIMESTAMPTZ DEFAULT NOW(),
  deleted BOOLEAN DEFAULT false,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_tasks_project ON tasks(project_id);
CREATE INDEX IF NOT EXISTS idx_tasks_series ON tasks(series_id);
CREATE INDEX IF NOT EXISTS idx_tasks_day ON tasks(day);
CREATE INDEX IF NOT EXISTS idx_tasks_status ON tasks(status);
CREATE INDEX IF NOT EXISTS idx_tasks_person ON tasks(person);

CREATE TABLE IF NOT EXISTS people (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT DEFAULT '',
  login TEXT DEFAULT '',
  birthday TEXT DEFAULT '',
  roles TEXT[] DEFAULT '{}',
  active BOOLEAN DEFAULT true,
  allow_parallel BOOLEAN DEFAULT false,
  deleted BOOLEAN DEFAULT false,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS roles (
  id TEXT PRIMARY KEY,
  label TEXT NOT NULL,
  color TEXT DEFAULT '#64748b',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS stages (
  id TEXT PRIMARY KEY,
  label TEXT NOT NULL,
  color TEXT DEFAULT '#64748b',
  "order" INTEGER DEFAULT 0,
  group_id TEXT DEFAULT '',
  needs_executor BOOLEAN DEFAULT true,
  roles_required TEXT[] DEFAULT '{}',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS stage_groups (
  id TEXT PRIMARY KEY,
  label TEXT NOT NULL,
  "order" INTEGER DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS holidays (
  date TEXT PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS audit_log (
  id SERIAL PRIMARY KEY,
  user_id INTEGER REFERENCES users(id),
  user_name TEXT NOT NULL DEFAULT '',
  action TEXT NOT NULL,
  entity TEXT NOT NULL,
  entity_id TEXT NOT NULL DEFAULT '',
  details JSONB DEFAULT '{}',
  created_at TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_audit_created ON audit_log(created_at DESC);
